def test_filter_transactions():
    # Тест на поиск по значению "EXECUTED"
    result = filter_transactions(transactions, r'EXECUTED')
    assert len(result) == 2
    assert all(transaction['state'] == 'EXECUTED' for transaction in result)

    # Тест на поиск по значению "CANCELED"
    result = filter_transactions(transactions, r'CANCELED')
    assert len(result) == 1
    assert all(transaction['state'] == 'CANCELED' for transaction in result)

    # Тест на поиск по регулярному выражению (начинается с "EXEC")
    result = filter_transactions(transactions, r'^EXEC')
    assert len(result) == 2
    assert all(transaction['state'].startswith('EXECUTED') for transaction in result)

    # Тест на случай, когда ничего не найдено
    result = filter_transactions(transactions, r'PENDING')
    assert len(result) == 0


